# Whitelisted endpoints
# ---------------------------------------------------------------------------

@frappe.whitelist(allow_guest=True, methods=["GET"])
def get_pin_login_status():
	"""Tell the POS whether to show the enrollment screen, the PIN keypad, or
	neither. Exposes no account list."""
	authenticated = frappe.session.user != "Guest"
	terminal = _resolve_terminal_from_cookie()

	if not terminal:
		return {
			"enabled": False,
			"authenticated": authenticated,
			"enrollment_required": not authenticated,
			"min_length": PIN_MIN_LENGTH,
			"max_length": PIN_MAX_LENGTH,
		}

	return {
		"enabled": bool(_eligible_settings(terminal.branch)),
		"authenticated": authenticated,
		"enrollment_required": False,
		"min_length": PIN_MIN_LENGTH,
		"max_length": PIN_MAX_LENGTH,
	}


@frappe.whitelist(methods=["POST"])
def generate_terminal_enrollment_code(terminal: str):
	"""Staff-only: mint a short-lived, single-use enrollment code shown in Desk
	and typed once on the device to bind it."""
	doc = frappe.get_doc(TERMINAL_DOCTYPE, terminal)
	if not frappe.has_permission(TERMINAL_DOCTYPE, "write", doc):
		frappe.throw(_("Not permitted"), frappe.PermissionError)

	raw_code = doc.issue_enrollment_code()
	return {
		"terminal_id": doc.terminal_id,
		"code": raw_code,
		"expires_in_minutes": ENROLLMENT_CODE_TTL_MINUTES,
	}


@frappe.whitelist(allow_guest=True, methods=["POST"])
@rate_limit(limit=10, seconds=60 * 60, methods=["POST"], ip_based=True)
def enroll_terminal(terminal_id: str, code: str):
	"""Guest device: exchange a valid enrollment code for a device credential,
	returned as an httpOnly cookie. The raw code is single use."""
	terminal_id = str(terminal_id or "").strip()
	code = str(code or "").strip()
	if not terminal_id or not code:
		frappe.throw(_(GENERIC_ENROLL_ERROR), frappe.AuthenticationError)

	name = frappe.db.get_value(
		TERMINAL_DOCTYPE, {"terminal_id": terminal_id, "enabled": 1}, "name"
	)
	if not name:
		frappe.throw(_(GENERIC_ENROLL_ERROR), frappe.AuthenticationError)

	terminal = frappe.get_doc(TERMINAL_DOCTYPE, name)
	if not terminal.verify_enrollment_code(code):
		frappe.throw(_(GENERIC_ENROLL_ERROR), frappe.AuthenticationError)

	raw_credential = terminal.issue_credential()
	terminal.touch_last_seen()
	_set_terminal_cookie(raw_credential)
	frappe.db.commit()  # nosemgrep

	return {
		"terminal_id": terminal.terminal_id,
		"terminal_name": terminal.terminal_name,
		"branch": terminal.branch,
	}


@frappe.whitelist(allow_guest=True, methods=["POST"])
@rate_limit(limit=5, seconds=60, methods=["POST"], ip_based=True)
def login_with_pin(pin: str):
	"""Create a real Frappe user session after verifying a personal POS PIN on
	an enrolled terminal."""
	# The POS lock action logs out first, so accept PINs only from Guest.
	if frappe.session.user != "Guest":
		frappe.throw(_("Log out before switching POS users."), frappe.PermissionError)

	terminal = _resolve_terminal_from_cookie()
	if not terminal:
		_reject_pin_login(reason="no_terminal")

	if _is_terminal_locked(terminal.terminal_id):
		_reject_pin_login(terminal=terminal, reason="locked", audit_status="Locked")

	pin = str(pin or "").strip()
	if not pin.isdigit() or not PIN_MIN_LENGTH <= len(pin) <= PIN_MAX_LENGTH:
		_register_terminal_failure(terminal.terminal_id)
		_reject_pin_login(terminal=terminal, reason="bad_format")

	user = _find_user_for_pin(pin, terminal.branch)
	if not user:
		_register_terminal_failure(terminal.terminal_id)
		_reject_pin_login(terminal=terminal, reason="no_match")

	# Re-check eligibility immediately before creating the session so disabling a
	# user, role, Branch assignment, or PIN setting takes effect without delay.
	if not is_eligible_pos_user(user) or not is_user_in_branch(user, terminal.branch):
		_register_terminal_failure(terminal.terminal_id)
		_reject_pin_login(terminal=terminal, reason="ineligible")

	_clear_terminal_failures(terminal.terminal_id)
	terminal.touch_last_seen()

	login_manager = getattr(frappe.local, "login_manager", None) or LoginManager()
	login_manager.login_as(user)
	_record_login("Logged in to URY POS with personal PIN", user, "Success")
	_record_audit("Success", terminal=terminal, user=user, reason="pin_login")

	return {
		"user": user,
		"full_name": frappe.utils.get_fullname(user),
		"redirect_to": "/pos",
	}
